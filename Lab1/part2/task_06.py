# Завдання 6. Складіть програму підрахунку площі рівнобедреного трикутника.
# Якщо площа трикутника парна, розділити її на 2, в іншому випадку вивести
# повідомлення «Не можу ділити на 2!»

import math    # підключаємо модуль math, у якому є функція sqrt() - квадратний корінь

# Вводимо бічну сторону та основу рівнобедреного трикутника
a = float(input("Enter the lateral side a: "))
b = float(input("Enter the base b: "))

# Перевіряємо, чи існує такий трикутник:
# сторони мають бути додатними, а сума двох бічних сторін - більшою за основу
if a > 0 and b > 0 and 2 * a > b:
    # Висоту, проведену до основи, знаходимо за теоремою Піфагора:
    # вона ділить основу навпіл, тому h = sqrt(a^2 - (b/2)^2)
    h = math.sqrt(a ** 2 - (b / 2) ** 2)

    # Площа трикутника дорівнює половині добутку основи на висоту
    s = b * h / 2
    print("Area of the triangle:", round(s, 4))

    # Площа парна, якщо вона ділиться на 2 без остачі
    if s % 2 == 0:
        print("The area is even. Area divided by 2:", s / 2)
    else:
        print("I can't divide by 2!")
else:
    print("A triangle with such sides does not exist")
