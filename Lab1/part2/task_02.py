# Завдання 2. Дано номер року (позитивне ціле число). Визначити кількість
# днів в цьому році, враховуючи, що звичайний рік нараховує 365 днів,
# а високосний - 366 днів. Високосним вважається рік, що ділиться на 4,
# за винятком тих років, які діляться на 100 і не діляться на 400.

# Вводимо номер року з клавіатури
year = int(input("Enter the year: "))

# Рік високосний, якщо він ділиться на 4 і при цьому
# або не ділиться на 100, або ділиться на 400.
# Оператор % повертає остачу від ділення: якщо вона 0, число ділиться націло.
if year % 4 == 0 and (year % 100 != 0 or year % 400 == 0):
    days = 366    # високосний рік
else:
    days = 365    # звичайний рік

print("Number of days in the year", year, "is", days)
