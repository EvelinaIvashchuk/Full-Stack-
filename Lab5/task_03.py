# починатися з фрази: «Python можна використати для ...». Збережіть файл з
# ім'ям learning_python.txt. Напишіть програму, яка зчитує файл і виводить
# текст з перебором рядків файла і зі збереженням рядків у списку з подальшим
# сортуванням списку за довжиною рядків в ньому від найбільшого до найменшого.

import os    # модуль для роботи з файловою системою

# Робимо поточним каталог, у якому лежить програма
os.chdir(os.path.dirname(os.path.abspath(__file__)))

lines = []    # список для рядків файла

print("Text of the file:")

# Відкриваємо файл для читання і перебираємо його рядки циклом for
with open("learning_python.txt", "r", encoding="utf-8") as file:
    for line in file:
        line = line.strip()    # прибираємо символ нового рядка в кінці
        print(line)            # виводимо рядок на екран
        lines.append(line)     # зберігаємо рядок у списку

# Сортуємо список за довжиною рядків: key=len означає, що рядки порівнюються
# за значенням функції len(), а reverse=True задає порядок від найбільшого
lines.sort(key=len, reverse=True)

print()
print("Lines sorted by length (from the longest to the shortest):")
for line in lines:
    print(len(line), "-", line)
