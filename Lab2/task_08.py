# Завдання 8. Визначити, скільки разів в тексті зустрічається задане слово.

# Вводимо текст і слово з клавіатури
text = input("Enter the text: ")
search = input("Enter the word: ")

# Переводимо слово в нижній регістр, щоб пошук не залежав від регістру
search = search.lower()

count = 0    # лічильник знайдених слів

# Розбиваємо текст на слова і порівнюємо кожне слово із заданим
for word in text.split():
    # strip() прибирає розділові знаки з початку і кінця слова,
    # щоб, наприклад, "слово," теж вважалося словом "слово"
    word = word.strip('.,!?;:()"').lower()
    if word == search:
        count += 1

print("The word", search, "occurs in the text", count, "times")
