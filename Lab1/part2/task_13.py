# Завдання 13. Знайти суму квадратів всіх цілих чисел від a до 50 (значення a
# вводиться з клавіатури; 0 <= a <= 50). Вирішити задачу використовуючи
# циклічну конструкцію for.

# Вводимо число a з клавіатури
a = int(input("Enter the number a (0 <= a <= 50): "))

# Перевіряємо умову 0 <= a <= 50
if 0 <= a <= 50:
    total = 0    # змінна для накопичення суми квадратів, спочатку дорівнює 0

    # range(a, 51) дає числа від a до 50 включно:
    # верхня межа в range не входить, тому пишемо 51
    for i in range(a, 51):
        total += i ** 2    # додаємо до суми квадрат чергового числа

    print("The sum of squares of integers from", a, "to 50 is", total)
else:
    print("Error: a must be in the range from 0 to 50")
