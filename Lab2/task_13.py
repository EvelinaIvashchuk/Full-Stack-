# Завдання 13. Дано рядок на англійській мові, що містить текст (до тисячі
# слів). Написати програму, що повертає список, який містить всі імена і
# власні назви всередині речень (слова з великої літери).


def find_proper_names(text):
    # Функція повертає список слів з великої літери, які стоять усередині речень
    names = []               # список знайдених імен і власних назв
    sentence_start = True    # чи є поточне слово першим словом речення

    for word in text.split():
        # Прибираємо розділові знаки з початку і кінця слова
        clean_word = word.strip('.,!?;:()"')

        # Перевіряємо, чи починається слово з великої літери (порожнє слово пропускаємо)
        is_capital = clean_word != "" and clean_word[0].isupper()

        # Додаємо слово до списку, якщо воно з великої літери і не на початку речення.
        # Займенник "I" завжди пишеться з великої літери, але не є власною назвою.
        if is_capital and not sentence_start and clean_word != "I":
            names.append(clean_word)

        # Якщо слово закінчується на ".", "!" або "?", наступне слово починає нове речення
        sentence_start = word.endswith(".") or word.endswith("!") or word.endswith("?")

    return names


# Вводимо текст з клавіатури і викликаємо функцію
text = input("Enter the text: ")
result = find_proper_names(text)

print("Names and proper nouns:", result)
