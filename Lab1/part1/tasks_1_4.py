# Завдання 1. Створіть чотири змінні. За допомогою функції input присвойте
# змінним значення з цілих і дробових чисел.

# input() повертає рядок, тому перетворюємо його: int() - ціле, float() - дробове
a = int(input("Enter an integer number a: "))
b = int(input("Enter an integer number b: "))
c = float(input("Enter a fractional number c: "))
d = float(input("Enter a fractional number d: "))

# Виводимо значення змінних та їх типи для перевірки
print("a =", a, type(a))
print("b =", b, type(b))
print("c =", c, type(c))
print("d =", d, type(d))

# Завдання 2. Виконайте над числами наступні дії:
#   - додавання
#   - віднімання
#   - множення
#   - ділення
#   - піднесення до ступеня
#   - цілочисленне ділення
#   - остача від ділення двох чисел
# Отримані відповіді запишіть в список.

results = [
    a + b,    # додавання
    c - d,    # віднімання
    a * c,    # множення
    b / d,    # ділення (d не повинно дорівнювати 0)
    a ** b,   # піднесення до степеня
    c // d,   # цілочисельне ділення
    a % b     # остача від ділення (b не повинно дорівнювати 0)
]

print("\nResult list:", results)

# Завдання 3. Визначте кількість елементів у попередньому списку.
# Виведіть на екран парні елементи списку.

# Кількість елементів списку визначаємо функцією len()
print("\nNumber of elements in the list:", len(results))

# Варіант 1: елементи на парних позиціях (2-й, 4-й, 6-й) - це індекси 1, 3, 5,
# бо індексація починається з 0. Зріз [1::2] бере кожен другий елемент з індексу 1.
print("Elements at even positions:", results[1::2])

# Варіант 2: елементи з парними значеннями (діляться на 2 без остачі)
even = []                  # порожній список для парних значень
for x in results:          # перебираємо кожен елемент списку
    if x % 2 == 0:         # якщо остача від ділення на 2 дорівнює 0
        even.append(x)     # додаємо елемент до списку even
print("Elements with even values:", even)

# Завдання 4. Поміняйте місцями другий і п'ятий елементи попереднього списку.
# Виведіть на екран отриманий список.

# 2-й елемент має індекс 1, 5-й - індекс 4. Міняємо їх місцями одним рядком.
results[1], results[4] = results[4], results[1]

print("\nList after swapping the 2nd and 5th elements:", results)
