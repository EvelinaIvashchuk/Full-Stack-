# Завдання 7. Дано рядок. Перетворити його, замінивши зірочками всі букви "п",
# що зустрічаються серед перших n / 2 символів. Тут n - довжина рядка.

# Вводимо рядок з клавіатури (літера "п" - українська)
text = input("Enter the text: ")

n = len(text)     # довжина рядка
half = n // 2     # кількість символів у першій половині (цілочисельне ділення)

# Ділимо рядок на дві частини за допомогою зрізів:
# text[:half] - перші half символів, text[half:] - решта рядка
first_part = text[:half]
second_part = text[half:]

# Замінюємо букви "п" зірочками лише в першій частині
first_part = first_part.replace("п", "*")

# З'єднуємо частини назад в один рядок
new_text = first_part + second_part

print("Length of the string:", n)
print("New text:", new_text)
