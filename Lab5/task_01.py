# Завдання 1. Створіть новий файл numbers.txt у текстовому редакторі і
# запишіть у нього 10 чисел, кожне з нового рядка. Напишіть програму, яка
# зчитує ці числа з файла і обчислює їх суму, виводить цю суму на екран і,
# водночас, записує цю суму у інший файл з назвою sum_numbers.txt.

import os    # модуль для роботи з файловою системою

# Робимо поточним каталог, у якому лежить програма, щоб файли шукалися поруч з нею
os.chdir(os.path.dirname(os.path.abspath(__file__)))

total = 0    # сума чисел

# Відкриваємо файл для читання ("r"). Конструкція with сама закриє файл
# після завершення блоку, навіть якщо виникне помилка.
with open("numbers.txt", "r", encoding="utf-8") as file:
    # Файл можна перебирати циклом for: на кожному кроці отримуємо один рядок
    for line in file:
        # strip() прибирає символ нового рядка; порожні рядки пропускаємо
        line = line.strip()
        if line != "":
            total += float(line)    # перетворюємо рядок у число і додаємо до суми

print("Sum of the numbers:", total)

# Відкриваємо файл для запису ("w"): якщо файла немає, він буде створений,
# якщо є - його вміст буде замінено
with open("sum_numbers.txt", "w", encoding="utf-8") as file:
    # write() записує у файл тільки рядки, тому число перетворюємо функцією str()
    file.write("Sum of the numbers: " + str(total) + "\n")

print("The sum is saved to the file sum_numbers.txt")
