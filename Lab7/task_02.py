# Завдання 2. Напишіть клас Coin, який описує монету, яку можна підкидати.
# При створенні екземпляру класу екземпляр отримує атрибут __sideup зі
# значенням heads або tails. У класі визначте метод toss, який випадково
# визначає результат підкидання монети - орел чи решка. Створіть екземпляр
# класу і виведіть на екран n підкидань монети.

import random    # модуль для отримання випадкових значень


class Coin:
    # Клас описує монету, яку можна підкидати

    def __init__(self):
        # Прихований атрибут __sideup зберігає сторону, якою монета лежить догори.
        # Спочатку монета лежить орлом (heads) догори.
        self.__sideup = "heads"

    def toss(self):
        # Метод підкидає монету: random.choice() випадково обирає
        # один елемент зі списку
        self.__sideup = random.choice(["heads", "tails"])

    def get_sideup(self):
        # Метод повертає сторону, якою монета лежить догори
        return self.__sideup


# Створюємо екземпляр класу
coin = Coin()
print("The initial side:", coin.get_sideup())

# Вводимо кількість підкидань
n = int(input("Enter the number of tosses: "))

# Підкидаємо монету n разів і виводимо результат кожного підкидання
for i in range(1, n + 1):
    coin.toss()
    print("Toss", i, ":", coin.get_sideup())
