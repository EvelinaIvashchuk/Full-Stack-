# Завдання 15. Серед чисел 1, 4, 9, 16, 25, ... знайти перше число, більше n.
# Вирішити задачу використовуючи циклічну конструкцію for.

# Вводимо число n з клавіатури
n = int(input("Enter the number n: "))

# Числа 1, 4, 9, 16, 25, ... - це квадрати натуральних чисел: 1^2, 2^2, 3^2, ...
# Перебираємо i = 1, 2, 3, ... і перевіряємо квадрат кожного числа.
# Квадрат числа (n + 1) завжди більший за n, тому діапазону до abs(n) + 2
# гарантовано вистачить (abs() потрібен на випадок від'ємного n).
for i in range(1, abs(n) + 2):
    if i ** 2 > n:                                  # якщо квадрат більший за n
        print("The first number greater than", n, "is", i ** 2)
        break                                       # число знайдено - виходимо з циклу
