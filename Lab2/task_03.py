# Завдання 3. В тексті видалити символ крапки (.) і підрахувати кількість
# видалених символів.

# Вводимо текст з клавіатури
text = input("Enter the text: ")

# Кількість видалених символів дорівнює кількості крапок у тексті
count = text.count(".")

# Щоб видалити символ, замінюємо його на порожній рядок ""
new_text = text.replace(".", "")

print("New text:", new_text)
print("Number of deleted characters:", count)
