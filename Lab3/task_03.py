# Завдання 3. В списку довжиною 20 обчислити суму елементів з непарними
# індексами. Вивести на екран список, отриману суму.

import random    # модуль для отримання випадкових чисел

numbers = []    # порожній список

# Заповнюємо список 20 випадковими цілими числами від -100 до 100.
# Функція randint(a, b) повертає випадкове ціле число від a до b включно.
for i in range(20):
    numbers.append(random.randint(-100, 100))

total = 0    # сума елементів з непарними індексами

# range(1, 20, 2) дає непарні індекси: 1, 3, 5, ..., 19
for i in range(1, 20, 2):
    total += numbers[i]

print("List:", numbers)
print("Elements with odd indices:", numbers[1::2])
print("Sum of elements with odd indices:", total)
