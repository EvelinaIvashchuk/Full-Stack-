# Завдання 3. Напишіть клас Car, який надає для створених екземплярів такі
# атрибути даних автомобіля: марку виготовлення автомобіля, модель
# автомобіля, рік автомобіля, швидкість (початкове значення 0). Клас також
# повинен мати наступні методи: accelerate (щоразу додає 5 до швидкості),
# brake (щоразу віднімає 5 від швидкості), get_speed (повертає поточну
# швидкість). Створіть екземпляр класу Car і викличте метод accelerate п'ять
# разів, після кожного виклику надрукуйте поточну швидкість. Потім викличте
# метод brake п'ять разів, після кожного виклику надрукуйте поточну швидкість.


class Car:
    # Клас описує автомобіль

    def __init__(self, make, model, year):
        self.make = make      # марка автомобіля
        self.model = model    # модель автомобіля
        self.year = year      # рік випуску
        self.speed = 0        # швидкість, початкове значення 0

    def accelerate(self):
        # Метод збільшує швидкість на 5
        self.speed += 5

    def brake(self):
        # Метод зменшує швидкість на 5
        self.speed -= 5

    def get_speed(self):
        # Метод повертає поточну швидкість
        return self.speed


# Створюємо екземпляр класу Car
car = Car("Toyota", "Corolla", 2020)
print("Car:", car.make, car.model, car.year)
print("Initial speed:", car.get_speed())

# П'ять разів викликаємо метод accelerate і після кожного виклику виводимо швидкість
for i in range(5):
    car.accelerate()
    print("Speed after accelerating:", car.get_speed())

# П'ять разів викликаємо метод brake і після кожного виклику виводимо швидкість
for i in range(5):
    car.brake()
    print("Speed after braking:", car.get_speed())
