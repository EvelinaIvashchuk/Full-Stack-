# Завдання 5. Сформувати список з 30 випадкових цілих чисел від -100 до +100.
# Вивести пари від'ємних чисел, що стоять поруч.

import random    # модуль для отримання випадкових чисел

numbers = []    # порожній список

# Формуємо список з 30 випадкових цілих чисел від -100 до 100
for i in range(30):
    numbers.append(random.randint(-100, 100))

print("List:", numbers)
print("Pairs of adjacent negative numbers:")

count = 0    # кількість знайдених пар

# Порівнюємо кожен елемент з наступним, тому останній індекс - передостанній елемент:
# range(len(numbers) - 1) дає індекси від 0 до 28
for i in range(len(numbers) - 1):
    # Пара підходить, якщо обидва сусідні числа від'ємні
    if numbers[i] < 0 and numbers[i + 1] < 0:
        print(numbers[i], numbers[i + 1])
        count += 1

# Якщо жодної пари не знайдено, повідомляємо про це
if count == 0:
    print("There are no such pairs")
