# Завдання 14. Дано ціле число N (> 1). Знайти найменше ціле число K, при
# якому виконується нерівність 5 ^ K > N. Вирішити задачу використовуючи
# циклічну конструкцію while.

# Вводимо число N з клавіатури
n = int(input("Enter the integer number N (N > 1): "))

# Перевіряємо умову N > 1
if n > 1:
    k = 0    # починаємо перевірку з K = 0

    # Поки 5 в степені K не перевищує N, збільшуємо K на 1.
    # Цикл завершиться, щойно 5 ** k стане більшим за N.
    while 5 ** k <= n:
        k += 1

    print("The smallest K is", k)
    print("Check: 5 **", k, "=", 5 ** k, ">", n)
else:
    print("Error: N must be greater than 1")
