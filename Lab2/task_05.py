# Завдання 5. У рядку замінити всі великі літери малими.

# Вводимо рядок з клавіатури
text = input("Enter the text: ")

# Метод lower() повертає новий рядок, у якому всі великі літери замінено малими
new_text = text.lower()

print("New text:", new_text)
