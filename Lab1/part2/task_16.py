# Завдання 16. Серед чисел 1, 5, 10, 17, 26, ... знайти перше число, більше n.
# Умовний оператор не використовувати. Вирішити задачу використовуючи
# циклічну конструкцію while.

# Вводимо число n з клавіатури
n = int(input("Enter the number n: "))

# Перше число послідовності дорівнює 1, а наступні (5, 10, 17, 26, ...)
# обчислюються за формулою k^2 + 1 при k = 2, 3, 4, 5, ...
number = 1    # поточне число послідовності
k = 2         # значення k для обчислення наступного числа

# Поки поточне число не перевищує n, переходимо до наступного числа.
# Умова циклу замінює умовний оператор if.
while number <= n:
    number = k ** 2 + 1    # обчислюємо наступне число послідовності
    k += 1                 # збільшуємо k для наступного кроку

print("The first number greater than", n, "is", number)
