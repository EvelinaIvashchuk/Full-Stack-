# Завдання 6. У рядку видалити всі літери "о" і підрахувати кількість
# видалених символів.

# Вводимо рядок з клавіатури (літера "о" - українська)
text = input("Enter the text: ")

# Рахуємо і малі, і великі літери "о"
count = text.count("о") + text.count("О")

# Видаляємо літери, замінюючи їх на порожній рядок
new_text = text.replace("о", "").replace("О", "")

print("New text:", new_text)
print("Number of deleted characters:", count)
