# Завдання 1. Дано рядок, що містить текст (до тисячі слів). Знайти кількість
# слів, що починаються з заданої користувачем літери без врахування регістру.

# Вводимо текст і літеру з клавіатури
text = input("Enter the text: ")
letter = input("Enter the letter: ")

# Переводимо літеру в нижній регістр, щоб порівняння не залежало від регістру
letter = letter.lower()

count = 0    # лічильник слів, що починаються із заданої літери

# split() розбиває рядок на слова за пробілами і повертає список слів
for word in text.split():
    # strip() прибирає розділові знаки з початку і кінця слова (лапки, дужки тощо),
    # lower() переводить слово в нижній регістр
    word = word.strip('.,!?;:()"«»').lower()
    if word.startswith(letter):
        count += 1

print("Number of words starting with", letter, ":", count)
