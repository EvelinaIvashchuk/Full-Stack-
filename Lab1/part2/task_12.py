# Завдання 12. Знайти суму всіх цілих чисел від a до b (значення a і b
# вводяться з клавіатури; b >= a). Вирішити задачу використовуючи циклічну
# конструкцію while.

# Вводимо числа a і b з клавіатури
a = int(input("Enter the number a: "))
b = int(input("Enter the number b (b >= a): "))

# Перевіряємо умову b >= a
if b >= a:
    total = 0    # змінна для накопичення суми, спочатку дорівнює 0
    i = a        # лічильник циклу, починаємо з числа a

    # Цикл виконується, поки i не перевищить b
    while i <= b:
        total += i    # додаємо поточне число до суми
        i += 1        # переходимо до наступного числа

    print("The sum of integers from", a, "to", b, "is", total)
else:
    print("Error: b must be greater than or equal to a")
