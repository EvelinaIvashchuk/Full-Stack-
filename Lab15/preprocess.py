# Модуль preprocess містить функцію очищення тексту. Її використовують і
# програма навчання моделі, і веб-додаток, щоб текст користувача оброблявся
# так само, як тексти, на яких навчалася модель.

import re    # регулярні вирази


def clean_text(text):
    # Функція готує текст до класифікації
    text = text.lower()                          # переводимо в нижній регістр
    text = re.sub(r"http\S+", " url ", text)     # посилання замінюємо словом url
    text = re.sub(r"\S+@\S+", " email ", text)   # електронні адреси - словом email
    text = re.sub(r"[^a-zA-Z ]", " ", text)      # залишаємо лише латинські літери
    text = re.sub(r"\s+", " ", text).strip()     # прибираємо зайві пробіли
    return text
