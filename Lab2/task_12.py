# Завдання 12. Дано рядок на англійській мові, що містить текст (до тисячі
# слів). Написати програму для підрахунку приголосних літер в тексті.
# Програма має бути нечутлива до регістру.

# Вводимо текст з клавіатури
text = input("Enter the text: ")

consonants = "bcdfghjklmnpqrstvwxyz"    # приголосні літери англійського алфавіту

count = 0    # лічильник приголосних

# Переводимо текст у нижній регістр і перебираємо його посимвольно.
# Пробіли, цифри та розділові знаки не входять до рядка consonants,
# тому вони не рахуються.
for char in text.lower():
    if char in consonants:
        count += 1

print("Number of consonants:", count)
